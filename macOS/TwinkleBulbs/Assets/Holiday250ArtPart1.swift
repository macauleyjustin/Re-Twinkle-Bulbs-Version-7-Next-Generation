            let p = CGMutablePath()
            p.move(to: CGPoint(x: 12 * s, y: 10 * s))
            p.addLine(to: CGPoint(x: 9 * s, y: 19 * s))
            p.addQuadCurve(to: CGPoint(x: 16 * s, y: 30.5 * s), control: CGPoint(x: 11 * s, y: 29.5 * s))
            p.addQuadCurve(to: CGPoint(x: 23 * s, y: 19 * s), control: CGPoint(x: 21 * s, y: 29.5 * s))
            p.addLine(to: CGPoint(x: 20 * s, y: 10 * s))
            p.closeSubpath()
            fillAndStroke(ctx, path: p, fill: col, stroke: rim, lineW: 1.1 * s)
            ctx.setStrokeColor(NSColor.white.withAlphaComponent(lit ? 0.55 : 0.15).cgColor)
            ctx.move(to: CGPoint(x: 15 * s, y: 12 * s)); ctx.addLine(to: CGPoint(x: 14 * s, y: 26 * s)); ctx.strokePath()

        case 3: // Miniature incandescent (narrow pointed mini-bulb w/ collar)
            drawSocket(5, 4.5, 6.5)
            ctx.setFillColor(white.withAlphaComponent(0.7).cgColor)
            ctx.fill(CGRect(x: 13.5 * s, y: 11.2 * s, width: 5 * s, height: 1.5 * s))
