            ctx.addPath(p); ctx.setLineWidth(3.2 * s); ctx.setStrokeColor(red.cgColor); ctx.setLineDash(phase: 0, lengths: [3.2 * s, 3.2 * s]); ctx.strokePath()
            ctx.setLineDash(phase: 0, lengths: []); ctx.setLineCap(.butt)

        case 12: // Holly sprig (3 serrated dark green leaves + 3 red berries)
            for (dx, ang) in [(-5.0, -0.4), (5.0, 0.4), (0.0, 0.0)] {
