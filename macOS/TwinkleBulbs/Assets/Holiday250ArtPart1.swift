            dome.closeSubpath()
            fillAndStroke(ctx, path: dome, fill: col, stroke: rim, lineW: s)
            ctx.setFillColor(white.cgColor)
            ctx.fillEllipse(in: CGRect(x: 13.5 * s, y: 7.5 * s, width: 5 * s, height: 5 * s))
            ctx.fill(CGRect(x: 6.5 * s, y: 21 * s, width: 19 * s, height: 5 * s))
            ctx.setStrokeColor(rim.cgColor); ctx.stroke(CGRect(x: 6.5 * s, y: 21 * s, width: 19 * s, height: 5 * s))

        case 25: // Winter scarf (neck loop + two fringed ends hanging down)
            ctx.setFillColor(col.cgColor)
            ctx.fillRoundedRect(CGRect(x: 7 * s, y: 8 * s, width: 18 * s, height: 6 * s), xRadius: 3 * s, yRadius: 3 * s)
            ctx.fill(CGRect(x: 10 * s, y: 13 * s, width: 5 * s, height: 14 * s))
            ctx.fill(CGRect(x: 17 * s, y: 13 * s, width: 5 * s, height: 11 * s))
            ctx.setFillColor(gold.cgColor)
            ctx.fill(CGRect(x: 10 * s, y: 19 * s, width: 5 * s, height: 2.5 * s))
            ctx.fill(CGRect(x: 17 * s, y: 17 * s, width: 5 * s, height: 2.5 * s))

        case 26: // Wooden sled (angled red/wood slats + silver runners)
            ctx.setStrokeColor(white.cgColor); ctx.setLineWidth(1.5 * s)
            ctx.move(to: CGPoint(x: 6 * s, y: 22 * s)); ctx.addQuadCurve(to: CGPoint(x: 24 * s, y: 25 * s), control: CGPoint(x: 27 * s, y: 25 * s)); ctx.strokePath()
            ctx.setFillColor(brown.cgColor); ctx.fill(CGRect(x: 7 * s, y: 16 * s, width: 16 * s, height: 3.5 * s))
            ctx.setFillColor(red.cgColor); ctx.fill(CGRect(x: 8 * s, y: 13.5 * s, width: 13 * s, height: 2.5 * s))

        case 27: // Ice skate (boot + ankle cuff + curved steel blade)
            let boot = CGMutablePath()
            boot.move(to: CGPoint(x: 9 * s, y: 8 * s)); boot.addLine(to: CGPoint(x: 16 * s, y: 8 * s))
            boot.addLine(to: CGPoint(x: 16 * s, y: 17 * s)); boot.addLine(to: CGPoint(x: 24 * s, y: 20 * s))
            boot.addLine(to: CGPoint(x: 24 * s, y: 24 * s)); boot.addLine(to: CGPoint(x: 9 * s, y: 24 * s)); boot.closeSubpath()
            fillAndStroke(ctx, path: boot, fill: col, stroke: rim, lineW: s)
            ctx.setStrokeColor(white.cgColor); ctx.setLineWidth(1.6 * s)
            ctx.move(to: CGPoint(x: 7 * s, y: 27.5 * s)); ctx.addLine(to: CGPoint(x: 26 * s, y: 27.5 * s)); ctx.strokePath()

        case 28: // Snowman (3 stacked white balls + top hat + carrot nose)
            ctx.setFillColor(white.cgColor)
