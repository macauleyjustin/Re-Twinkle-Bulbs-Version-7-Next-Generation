            p.move(to: CGPoint(x: 14 * s, y: 12.5 * s))
            p.addCurve(to: CGPoint(x: 16 * s, y: 28 * s), control1: CGPoint(x: 12 * s, y: 20 * s), control2: CGPoint(x: 14.5 * s, y: 28 * s))
