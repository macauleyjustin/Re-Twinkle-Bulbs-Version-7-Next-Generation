import Foundation
import CoreGraphics
import AppKit

extension Holiday250Catalog {
    static func drawBatch1_01_to_50(ctx: CGContext, n: Int, s: CGFloat, col: NSColor, rawPrimary: NSColor, rim: NSColor, lit: Bool, broken: Bool) {
        let sock = shade(NSColor(srgbRed: 0.08, green: 0.45, blue: 0.14, alpha: 1), lit: lit, darkFraction: 0.35)
        let gold = shade(NSColor(srgbRed: 0.96, green: 0.78, blue: 0.18, alpha: 1), lit: lit)
        let red = shade(NSColor(srgbRed: 0.92, green: 0.14, blue: 0.16, alpha: 1), lit: lit)
        let green = shade(NSColor(srgbRed: 0.14, green: 0.68, blue: 0.22, alpha: 1), lit: lit)
        let white = shade(NSColor(srgbRed: 0.96, green: 0.97, blue: 0.99, alpha: 1), lit: lit, darkFraction: 0.42)
        let brown = shade(NSColor(srgbRed: 0.56, green: 0.34, blue: 0.18, alpha: 1), lit: lit)

        func drawSocket(_ y: CGFloat = 5, _ w: CGFloat = 6, _ h: CGFloat = 5) {
            ctx.setFillColor(sock.cgColor)
            ctx.fill(CGRect(x: (16 - w * 0.5) * s, y: y * s, width: w * s, height: h * s))
            ctx.setStrokeColor(rim.cgColor); ctx.setLineWidth(s)
            ctx.stroke(CGRect(x: (16 - w * 0.5) * s, y: y * s, width: w * s, height: h * s))
        }

        switch n {
        // Collection 1 — Classic Christmas Lights (1..10)
        case 1: // C7 incandescent (conical brass/green screw socket, teardrop)
            drawSocket(5, 7, 5)
            let p = CGMutablePath()
            p.move(to: CGPoint(x: 13 * s, y: 10 * s))
            p.addCurve(to: CGPoint(x: 16 * s, y: 29 * s), control1: CGPoint(x: 8 * s, y: 19 * s), control2: CGPoint(x: 12 * s, y: 29 * s))
            p.addCurve(to: CGPoint(x: 19 * s, y: 10 * s), control1: CGPoint(x: 20 * s, y: 29 * s), control2: CGPoint(x: 24 * s, y: 19 * s))
            p.closeSubpath()
            fillAndStroke(ctx, path: p, fill: col, stroke: rim, lineW: s)
            if lit { ctx.setFillColor(NSColor.white.withAlphaComponent(0.65).cgColor); ctx.fillEllipse(in: CGRect(x: 12.5 * s, y: 13 * s, width: 2.6 * s, height: 5 * s)) }

        case 2: // C9 incandescent (larger faceted torpedo C9)
