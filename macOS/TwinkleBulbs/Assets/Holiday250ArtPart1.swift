                ctx.fillEllipse(in: CGRect(x: CGFloat(bx - 2.3) * s, y: CGFloat(by - 2.3) * s, width: 4.6 * s, height: 4.6 * s))
            }

        case 13: // Mistletoe (olive leaves + luminous white pearls)
            ctx.setFillColor(shade(NSColor(srgbRed: 0.22, green: 0.65, blue: 0.30, alpha: 1), lit: lit).cgColor)
            ctx.fillEllipse(in: CGRect(x: 6 * s, y: 10 * s, width: 10 * s, height: 16 * s))
            ctx.fillEllipse(in: CGRect(x: 16 * s, y: 10 * s, width: 10 * s, height: 16 * s))
            for (bx, by) in [(13.5, 22.0), (18.5, 22.0), (16.0, 26.0)] {
                ctx.setFillColor(white.cgColor)
                ctx.fillEllipse(in: CGRect(x: CGFloat(bx - 2.2) * s, y: CGFloat(by - 2.2) * s, width: 4.4 * s, height: 4.4 * s))
                ctx.setStrokeColor(rim.cgColor); ctx.setLineWidth(0.8 * s)
                ctx.strokeEllipse(in: CGRect(x: CGFloat(bx - 2.2) * s, y: CGFloat(by - 2.2) * s, width: 4.4 * s, height: 4.4 * s))
            }

        case 14: // Poinsettia (6 radial pointed petals + gold stamen dots)
            for i in 0..<6 {
                let a = CGFloat(i) * .pi / 3.0
                ctx.saveGState()
                ctx.translateBy(x: 16 * s, y: 18 * s)
                ctx.rotate(by: a)
                let p = CGMutablePath()
                p.move(to: .zero)
                p.addQuadCurve(to: CGPoint(x: 0, y: -11 * s), control: CGPoint(x: 5 * s, y: -6 * s))
                p.addQuadCurve(to: .zero, control: CGPoint(x: -5 * s, y: -6 * s))
                fillAndStroke(ctx, path: p, fill: col, stroke: rim, lineW: 0.8 * s)
                ctx.restoreGState()
            }
            ctx.setFillColor(gold.cgColor); ctx.fillEllipse(in: CGRect(x: 13.5 * s, y: 15.5 * s, width: 5 * s, height: 5 * s))

        case 15: // Pine cone (overlapping brown scales tapered downward)
            for row in 0..<4 {
                let y = CGFloat(8 + row * 5) * s
                let w = CGFloat(14 - row * 2) * s
                let r = CGRect(x: 16 * s - w * 0.5, y: y, width: w, height: 6.5 * s)
                ctx.setFillColor((row % 2 == 0 ? brown : shade(NSColor(srgbRed: 0.42, green: 0.24, blue: 0.12, alpha: 1), lit: lit)).cgColor)
                ctx.fillEllipse(in: r)
                ctx.setStrokeColor(rim.cgColor); ctx.setLineWidth(0.9 * s); ctx.strokeEllipse(in: r)
            }

        case 16: // Glass ornament (round bauble with silver cap + horizontal glitter stripe)
            ctx.setFillColor(gold.cgColor); ctx.fill(CGRect(x: 13 * s, y: 6 * s, width: 6 * s, height: 4 * s))
            let orb = CGRect(x: 7 * s, y: 9.5 * s, width: 18 * s, height: 18 * s)
            ctx.setFillColor(col.cgColor); ctx.fillEllipse(in: orb)
            ctx.setFillColor(gold.cgColor); ctx.fill(CGRect(x: 7.5 * s, y: 17.5 * s, width: 17 * s, height: 2.8 * s))
            ctx.setStrokeColor(rim.cgColor); ctx.setLineWidth(1.1 * s); ctx.strokeEllipse(in: orb)

        case 17: // Christmas bell (flared gold bell + spherical clapper)
            let p = CGMutablePath()
            p.move(to: CGPoint(x: 13 * s, y: 7 * s))
            p.addCurve(to: CGPoint(x: 7 * s, y: 24 * s), control1: CGPoint(x: 10 * s, y: 12 * s), control2: CGPoint(x: 10 * s, y: 19 * s))
            p.addLine(to: CGPoint(x: 25 * s, y: 24 * s))
            p.addCurve(to: CGPoint(x: 19 * s, y: 7 * s), control1: CGPoint(x: 22 * s, y: 19 * s), control2: CGPoint(x: 22 * s, y: 12 * s))
            p.closeSubpath()
            fillAndStroke(ctx, path: p, fill: gold, stroke: rim, lineW: 1.1 * s)
            ctx.setFillColor(red.cgColor); ctx.fillEllipse(in: CGRect(x: 14 * s, y: 24 * s, width: 4 * s, height: 4 * s))

        case 18: // Decorative bow (two ribbon loops + knot + two tail ends)
            let leftLoop = CGMutablePath()
            leftLoop.move(to: CGPoint(x: 16 * s, y: 14 * s))
            leftLoop.addCurve(to: CGPoint(x: 16 * s, y: 14 * s), control1: CGPoint(x: 4 * s, y: 5 * s), control2: CGPoint(x: 4 * s, y: 22 * s))
            let rightLoop = CGMutablePath()
            rightLoop.move(to: CGPoint(x: 16 * s, y: 14 * s))
            rightLoop.addCurve(to: CGPoint(x: 16 * s, y: 14 * s), control1: CGPoint(x: 28 * s, y: 5 * s), control2: CGPoint(x: 28 * s, y: 22 * s))
            fillAndStroke(ctx, path: leftLoop, fill: col, stroke: rim, lineW: s)
            fillAndStroke(ctx, path: rightLoop, fill: col, stroke: rim, lineW: s)
            ctx.setLineWidth(3 * s); ctx.setStrokeColor(col.cgColor)
            ctx.move(to: CGPoint(x: 15 * s, y: 15 * s)); ctx.addLine(to: CGPoint(x: 10 * s, y: 27 * s)); ctx.strokePath()
            ctx.move(to: CGPoint(x: 17 * s, y: 15 * s)); ctx.addLine(to: CGPoint(x: 22 * s, y: 27 * s)); ctx.strokePath()
            ctx.setFillColor(gold.cgColor); ctx.fillEllipse(in: CGRect(x: 13.5 * s, y: 11.5 * s, width: 5 * s, height: 5 * s))

        case 19: // Christmas stocking (cuffed vertical boot + toe curve)
            let p = CGMutablePath()
            p.move(to: CGPoint(x: 12 * s, y: 10 * s)); p.addLine(to: CGPoint(x: 12 * s, y: 21 * s))
            p.addLine(to: CGPoint(x: 7.5 * s, y: 24.5 * s))
            p.addArc(center: CGPoint(x: 10.5 * s, y: 26 * s), radius: 3.5 * s, startAngle: .pi * 0.7, endAngle: .pi * 0.2, clockwise: true)
            p.addLine(to: CGPoint(x: 21 * s, y: 28 * s)); p.addLine(to: CGPoint(x: 21 * s, y: 10 * s)); p.closeSubpath()
            fillAndStroke(ctx, path: p, fill: col, stroke: rim, lineW: s)
            ctx.setFillColor(white.cgColor); ctx.fill(CGRect(x: 11 * s, y: 7 * s, width: 11 * s, height: 4.5 * s))

        case 20: // Wrapped present (gift box + vertical/horizontal cross ribbon + top bow)
            let box = CGRect(x: 7 * s, y: 11 * s, width: 18 * s, height: 17 * s)
            ctx.setFillColor(col.cgColor); ctx.fill(box)
            ctx.setFillColor(gold.cgColor)
            ctx.fill(CGRect(x: 14.5 * s, y: 11 * s, width: 3 * s, height: 17 * s))
            ctx.fill(CGRect(x: 7 * s, y: 18 * s, width: 18 * s, height: 3 * s))
            ctx.fillEllipse(in: CGRect(x: 11 * s, y: 7 * s, width: 5 * s, height: 4 * s))
            ctx.fillEllipse(in: CGRect(x: 16 * s, y: 7 * s, width: 5 * s, height: 4 * s))
            ctx.setStrokeColor(rim.cgColor); ctx.setLineWidth(s); ctx.stroke(box)

        // Collection 3 — Winter Wonderland (21..30)
        case 21: // Snowflake (6 crystalline hex branches)
            ctx.setStrokeColor((lit ? col.blended(withFraction: 0.45, of: .white) ?? col : col).cgColor)
            ctx.setLineWidth(1.6 * s)
            let cx = 16 * s, cy = 18 * s
            for i in 0..<6 {
                let a = CGFloat(i) * .pi / 3.0
                let ex = cx + cos(a) * 10 * s, ey = cy + sin(a) * 10 * s
                ctx.move(to: CGPoint(x: cx, y: cy)); ctx.addLine(to: CGPoint(x: ex, y: ey))
                let mx = cx + cos(a) * 6.5 * s, my = cy + sin(a) * 6.5 * s
                ctx.move(to: CGPoint(x: mx, y: my)); ctx.addLine(to: CGPoint(x: mx + cos(a + 0.6) * 3 * s, y: my + sin(a + 0.6) * 3 * s))
                ctx.move(to: CGPoint(x: mx, y: my)); ctx.addLine(to: CGPoint(x: mx + cos(a - 0.6) * 3 * s, y: my + sin(a - 0.6) * 3 * s))
            }
            ctx.strokePath()

        case 22: // Icicle (multi-spike translucent crystal ice formation)
            let p = CGMutablePath()
            p.move(to: CGPoint(x: 8 * s, y: 6 * s))
            p.addLine(to: CGPoint(x: 11 * s, y: 20 * s)); p.addLine(to: CGPoint(x: 13 * s, y: 12 * s))
            p.addLine(to: CGPoint(x: 16 * s, y: 30 * s)); p.addLine(to: CGPoint(x: 19 * s, y: 13 * s))
