                ctx.rotate(by: CGFloat(ang))
                ctx.setFillColor(green.cgColor)
                ctx.fillEllipse(in: CGRect(x: -4 * s, y: -6 * s, width: 8 * s, height: 12 * s))
                ctx.restoreGState()
            }
            for (bx, by) in [(13.5, 19.0), (18.5, 19.0), (16.0, 23.0)] {
