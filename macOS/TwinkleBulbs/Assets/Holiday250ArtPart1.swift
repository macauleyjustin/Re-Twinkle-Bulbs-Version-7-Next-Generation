            let fillFrosted = col.blended(withFraction: 0.35, of: .white) ?? col
            ctx.setFillColor(fillFrosted.cgColor)
            ctx.fillEllipse(in: rect)
            ctx.setStrokeColor(white.cgColor); ctx.setLineWidth(1.5 * s)
            ctx.strokeEllipse(in: rect)

        case 6: // Transparent glass globe (clear outer glass ring + visible tungsten filament!)
            drawSocket(5, 6, 5)
            let globe = CGRect(x: 8.5 * s, y: 9.5 * s, width: 15 * s, height: 15 * s)
            ctx.setFillColor((lit ? col.withAlphaComponent(0.45) : NSColor(white: 0.25, alpha: 0.35)).cgColor)
            ctx.fillEllipse(in: globe)
            ctx.setStrokeColor(col.cgColor); ctx.setLineWidth(1.5 * s)
            ctx.strokeEllipse(in: globe)
            ctx.setStrokeColor((lit ? gold : rim).cgColor); ctx.setLineWidth(1.2 * s)
            ctx.move(to: CGPoint(x: 14 * s, y: 10 * s)); ctx.addLine(to: CGPoint(x: 14 * s, y: 16 * s))
            ctx.addLine(to: CGPoint(x: 16 * s, y: 14.5 * s)); ctx.addLine(to: CGPoint(x: 18 * s, y: 16 * s))
            ctx.addLine(to: CGPoint(x: 18 * s, y: 10 * s)); ctx.strokePath()

        case 7: // Ceramic opaque bulb (matte saturated dome, bold outline, soft top shine)
            drawSocket(5, 7, 5)
            let r = CGRect(x: 9 * s, y: 10 * s, width: 14 * s, height: 17.5 * s)
            ctx.setFillColor((lit ? rawPrimary.blended(withFraction: 0.15, of: .white) ?? rawPrimary : col).cgColor)
            ctx.fillEllipse(in: r)
            ctx.setStrokeColor(rim.cgColor); ctx.setLineWidth(1.4 * s); ctx.strokeEllipse(in: r)

        case 8: // Icicle light (vertical fluted transparent ice tube)
            drawSocket(5, 4.5, 4)
            let p = CGMutablePath()
            p.move(to: CGPoint(x: 13.5 * s, y: 9 * s))
            p.addLine(to: CGPoint(x: 14.2 * s, y: 24 * s))
            p.addLine(to: CGPoint(x: 16 * s, y: 30.5 * s))
