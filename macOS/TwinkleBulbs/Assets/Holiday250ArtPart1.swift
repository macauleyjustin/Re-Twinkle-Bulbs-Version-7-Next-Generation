            fillAndStroke(ctx, path: p, fill: col, stroke: rim, lineW: s)

        case 4: // Faceted LED (diamond-cut octagonal prism dome)
            drawSocket(5, 7, 5.5)
            let p = CGMutablePath()
            p.move(to: CGPoint(x: 12.5 * s, y: 10.5 * s))
            p.addLine(to: CGPoint(x: 10.5 * s, y: 17 * s))
            p.addLine(to: CGPoint(x: 12 * s, y: 26.5 * s))
            p.addLine(to: CGPoint(x: 16 * s, y: 29 * s))
            p.addLine(to: CGPoint(x: 20 * s, y: 26.5 * s))
            p.addLine(to: CGPoint(x: 21.5 * s, y: 17 * s))
            p.addLine(to: CGPoint(x: 19.5 * s, y: 10.5 * s))
            p.closeSubpath()
            fillAndStroke(ctx, path: p, fill: col, stroke: rim, lineW: s)
